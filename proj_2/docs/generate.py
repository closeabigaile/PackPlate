"""Generate the WHAT docs from the code: docs/reference.md and docs/api.md.

Run from proj_2/ after changing a docstring, a function signature, or an API
route, and commit the result:

    python docs/generate.py            # rewrite both files
    python docs/generate.py --check    # fail if either is out of date (CI)

reference.md lists every public module, class, and function in backend/app,
db, ingestion, and eval, with its signature and docstring, read straight from
the source. api.md lists every HTTP endpoint and data model, read from the
API's own OpenAPI description, so neither can drift from the code.
"""

import argparse
import ast
import re
import sys
from pathlib import Path

PROJ = Path(__file__).resolve().parent.parent
DOCS = PROJ / "docs"
PACKAGES = [
    ("API", "backend/app", "app"),
    ("Database", "db", "db"),
    ("Scraper", "ingestion", "ingestion"),
    ("M0 loop 1", "eval", "eval"),
    ("M0 loop 2", "eval_loop2", "eval_loop2"),
]
SKIP_DIRS = {"tests", "migrations", "__pycache__"}
MISSING = "_No description yet._"
HEADER = (
    "<!-- Generated by docs/generate.py from the code. Don't edit by hand: "
    "change the code, then run `python docs/generate.py` from proj_2/. -->\n"
)


def slug(heading: str) -> str:
    """The anchor GitHub gives a heading: lowercase, punctuation dropped."""
    text = re.sub(r"[^\w\- ]", "", heading.lower())
    return text.replace(" ", "-")


def modules(src: str, dotted: str) -> list[tuple[str, Path]]:
    root = PROJ / src
    found = []
    for path in sorted(root.rglob("*.py")):
        rel = path.relative_to(root)
        if SKIP_DIRS & set(rel.parts):
            continue
        parts = [dotted, *rel.with_suffix("").parts]
        if parts[-1] == "__init__":
            parts = parts[:-1]
        found.append((".".join(parts), path))
    return found


def signature(node) -> str:
    lines = [f"@{ast.unparse(d)}" for d in node.decorator_list]
    returns = f" -> {ast.unparse(node.returns)}" if node.returns else ""
    prefix = "async def" if isinstance(node, ast.AsyncFunctionDef) else "def"
    lines.append(f"{prefix} {node.name}({ast.unparse(node.args)}){returns}")
    return "\n".join(lines)


def public(node) -> bool:
    return not node.name.startswith("_")


class Reference:
    def __init__(self):
        self.documented = self.total = 0
        self.out = []

    def doc(self, node) -> str:
        text = ast.get_docstring(node)
        self.total += 1
        self.documented += bool(text)
        if not text:
            return MISSING
        # Indented or column-aligned lines (rule tables, examples) would be
        # reflowed by Markdown, so show those docstrings exactly as written.
        if re.search(r"^[ \t]+\S|\S {3,}\S", text, re.M):
            return f"```text\n{text}\n```"
        return text

    def function(self, node, level: str):
        self.out += [f"{level} `{node.name}`", "", "```python", signature(node),
                     "```", "", self.doc(node), ""]  # fmt: skip

    def klass(self, node):
        bases = ", ".join(ast.unparse(b) for b in node.bases)
        title = f"class `{node.name}`" + (f" ({bases})" if bases else "")
        self.out += [f"### {title}", "", self.doc(node), ""]
        fields = [
            f"- `{ast.unparse(n.target)}: {ast.unparse(n.annotation)}`"
            for n in node.body
            if isinstance(n, ast.AnnAssign)
            and not ast.unparse(n.target).startswith("_")
        ]
        if fields:
            self.out += ["Fields:", "", *fields, ""]
        for n in node.body:
            if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and public(n):
                self.function(n, "####")

    def module(self, name: str, path: Path):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        rel = path.relative_to(PROJ).as_posix()
        self.out += [f"## `{name}`", "", f"Source: [`{rel}`](../{rel})", ""]
        self.out += [self.doc(tree), ""]
        for node in tree.body:
            if isinstance(node, ast.ClassDef) and public(node):
                self.klass(node)
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and public(
                node
            ):
                self.function(node, "###")


def reference() -> str:
    ref = Reference()
    toc = []
    for title, src, dotted in PACKAGES:
        if not (PROJ / src).is_dir():
            continue  # e.g. an eval loop that was removed
        found = modules(src, dotted)
        ref.out += [f"# {title}: `{src}/`", ""]
        toc.append(f"- **{title}** (`{src}/`)")
        for name, path in found:
            toc.append(f"  - [`{name}`](#{slug(name)})")
            ref.module(name, path)
    head = [
        HEADER,
        "# Code reference",
        "",
        "Every public module, class, and function in the Python code, with its "
        "signature and description, read from the source. The website "
        "(`frontend/`) is described in [how.md](how.md) instead.",
        "",
        f"**{ref.documented} of {ref.total}** modules, classes, and functions have "
        "a description.",
        "",
        *toc,
        "",
    ]
    return "\n".join(head + ref.out).rstrip() + "\n"


def schema_type(s: dict) -> str:
    if "$ref" in s:
        name = s["$ref"].rsplit("/", 1)[-1]
        return f"[{name}](#{slug(name)})"
    if "anyOf" in s:
        return " or ".join(schema_type(x) for x in s["anyOf"])
    if "enum" in s:
        return " / ".join(f"`{v}`" for v in s["enum"])
    if "const" in s:
        return f"`{s['const']}`"
    t = s.get("type", "any")
    if t == "array":
        return f"list of {schema_type(s.get('items', {}))}"
    if "format" in s:
        return f"{t} ({s['format']})"
    return t


def cell(text) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def api() -> str:
    sys.path[:0] = [str(PROJ / "backend"), str(PROJ)]
    from app.main import app

    spec = app.openapi()
    out = [
        HEADER,
        "# HTTP API",
        "",
        "Every endpoint and data model of the PackPlate API, read from the "
        "API's own OpenAPI description. A running API also serves this "
        "interactively at `/docs`.",
        "",
        "## Endpoints",
        "",
    ]
    for path, ops in spec["paths"].items():
        for method in ops:
            out.append(f"- [`{method.upper()} {path}`](#{slug(method + ' ' + path)})")
    out.append("")
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            out += [f"### `{method.upper()} {path}`", ""]
            out += [op.get("description") or op.get("summary") or MISSING, ""]
            params = op.get("parameters", [])
            if params:
                out += ["| Parameter | In | Type | Required | Default |",
                        "|---|---|---|---|---|"]  # fmt: skip
                for p in params:
                    s = p.get("schema", {})
                    default = f"`{s['default']}`" if "default" in s else ""
                    out.append(f"| `{p['name']}` | {p['in']} | {cell(schema_type(s))} "
                               f"| {'yes' if p.get('required') else 'no'} | {default} |")  # fmt: skip
                out.append("")
            body = op.get("requestBody")
            if body:
                s = body["content"]["application/json"]["schema"]
                out += [f"**Request body:** {schema_type(s)}", ""]
            out += ["| Response | Body |", "|---|---|"]
            for code, resp in op["responses"].items():
                s = resp.get("content", {}).get("application/json", {}).get("schema")
                shape = cell(schema_type(s)) if s else ""
                out.append(f"| {code} {cell(resp.get('description', ''))} | {shape} |")
            out.append("")
    out += ["## Data models", ""]
    for name, s in spec.get("components", {}).get("schemas", {}).items():
        out += [f"### {name}", ""]
        if s.get("description"):
            out += [s["description"], ""]
        props = s.get("properties", {})
        if props:
            required = set(s.get("required", []))
            out += ["| Field | Type | Required |", "|---|---|---|"]
            for field, fs in props.items():
                out.append(f"| `{field}` | {cell(schema_type(fs))} "
                           f"| {'yes' if field in required else 'no'} |")  # fmt: skip
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="fail if a generated file is out of date")  # fmt: skip
    args = parser.parse_args(argv)
    files = {DOCS / "reference.md": reference(), DOCS / "api.md": api()}
    stale = [p for p, text in files.items()
             if not p.exists() or p.read_text(encoding="utf-8") != text]  # fmt: skip
    if args.check:
        for p in stale:
            print(f"out of date: {p.relative_to(PROJ)}", file=sys.stderr)
        if stale:
            print("run `python docs/generate.py` from proj_2/ and commit the result",
                  file=sys.stderr)  # fmt: skip
        return 1 if stale else 0
    for p, text in files.items():
        p.write_text(text, encoding="utf-8", newline="\n")  # LF on every OS
        print(f"wrote {p.relative_to(PROJ)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
